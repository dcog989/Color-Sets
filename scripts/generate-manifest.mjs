import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const setsDir = join(__dirname, '..', 'src', 'lib', 'data', 'sets');
const outFile = join(__dirname, '..', 'src', 'lib', 'data', 'manifest.ts');

const files = readdirSync(setsDir)
    .filter((f) => f.endsWith('.json'))
    .sort();

const entries = files.map((file) => {
    const content = readFileSync(join(setsDir, file), 'utf-8');
    const json = JSON.parse(content);
    return { id: json.id, title: json.title, file, useNameAsBg: json.useNameAsBg ?? false };
});

const lines = [
    '// This file is auto-generated by scripts/generate-manifest.mjs.',
    '// Do not edit manually — changes will be overwritten.',
    '// Run `bun run manifest` to regenerate.',
    '',
    'export type SetManifestEntry = {',
    '    id: string;',
    '    title: string;',
    '    file: string;',
    '    useNameAsBg: boolean;',
    '};',
    '',
    'export const SET_MANIFEST: SetManifestEntry[] = [',
];

for (const e of entries) {
    const title = e.title;
    lines.push(
        `    { id: ${JSON.stringify(e.id)}, title: ${JSON.stringify(title)}, file: ${JSON.stringify(e.file)}, useNameAsBg: ${e.useNameAsBg} },`,
    );
}

lines.push('];');
lines.push('');

writeFileSync(outFile, lines.join('\n'));

console.log(`Generated manifest with ${entries.length} entries → ${outFile}`);
